@router.post("/multimodal")
async def search_multimodal(
    request: Request,
    file: UploadFile = File(...),
    query: str = Form(...),
    db: Session = Depends(get_db),
):
    """
    Search products using both an image and a text refinement.
    """

    # Start measuring the complete search operation.
    start_time = time.perf_counter()

    # Validate the uploaded file before reading it.
    if not file.content_type or not file.content_type.startswith("image/"):
        raise HTTPException(
            status_code=400,
            detail="Uploaded file must be an image.",
        )

    # Remove whitespace from the textual refinement.
    query = query.strip()

    # A multimodal search requires an actual textual refinement.
    if not query:
        raise HTTPException(
            status_code=400,
            detail="Search query cannot be empty.",
        )

    # Read the uploaded image.
    image_bytes = await file.read()

    # Decode and normalize the image into RGB.
    image = decode_uploaded_image(image_bytes)

    # Reuse the single CLIP model loaded during FastAPI startup.
    encoder = request.app.state.clip_encoder

    # Encode the image and text independently.
    image_embedding = encoder.encode_image(image)
    text_embedding = encoder.encode_text(query)

    # Combine both normalized CLIP representations using the configured
    # image/text weighting and normalize the resulting vector again.
    fused_embedding = fuse_embeddings(
        image_embedding=image_embedding,
        text_embedding=text_embedding,
    )

    # Search the fused representation against the same FAISS index.
    results = build_search_results(
        request=request,
        db=db,
        query_vector=fused_embedding,
    )

    # Calculate total search time.
    response_time_ms = (
        time.perf_counter() - start_time
    ) * 1000

    # Record the search in SQLite and Kafka.
    record_search_event(
        db=db,
        query_type="multimodal",
        query_text=query,
        results=results,
        response_time_ms=response_time_ms,
    )

    return {
        "query_type": "multimodal",
        "query": query,
        "image_weight": IMAGE_ALPHA,
        "text_weight": TEXT_ALPHA,
        "result_count": len(results),
        "results": results,
    }
